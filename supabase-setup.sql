create policy "Admins insert Mamlaka products" on public.mamlaka_products
 for insert to authenticated with check (exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())));
drop policy if exists "Admins update Mamlaka products" on public.mamlaka_products;
