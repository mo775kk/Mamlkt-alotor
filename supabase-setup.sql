-- مملكة العطور: إعداد قاعدة البيانات والحفظ السحابي
-- شغّله في SQL Editor على مشروع Supabase الخاص بالموقع.
-- بعد إنشاء مستخدم الإدارة في Authentication > Users، أضف UID الخاص به إلى public.admin_users.
-- لا تضع service_role أو secret key في ملفات الموقع.

create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

-- الجداول التي يستخدمها كود المزامنة الحالي في الموقع
create table if not exists public.mamlaka_products (
  id text primary key,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
create table if not exists public.mamlaka_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

-- جداول إدارة الكتالوج والطلبات والمخزون
create table if not exists public.catalog_items (
  id uuid primary key default gen_random_uuid(),
  name_ar text not null,
  name_en text,
  category text not null default 'غير محدد',
  scent_family text,
  product_type text not null default 'غير محدد',
  supplier text,
  description text,
  image_url text,
  price numeric(12,2) check (price is null or price >= 0),
  price_unit text not null default 'EGP',
  sizes jsonb not null default '[]'::jsonb check (jsonb_typeof(sizes) = 'array'),
  active boolean not null default true,
  sort_order integer not null default 0,
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists catalog_items_active_category_idx on public.catalog_items(active, category, sort_order);
create index if not exists catalog_items_name_ar_idx on public.catalog_items using gin (to_tsvector('simple', name_ar));

create table if not exists public.app_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);
create index if not exists app_settings_updated_by_idx on public.app_settings(updated_by);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_phone text not null,
  customer_address text,
  items jsonb not null default '[]'::jsonb check (jsonb_typeof(items) = 'array'),
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  delivery_fee numeric(12,2) not null default 0 check (delivery_fee >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  status text not null default 'new' check (status in ('new','confirmed','preparing','shipped','completed','cancelled')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists orders_status_idx on public.orders(status, created_at desc);

create table if not exists public.inventory_movements (
  id uuid primary key default gen_random_uuid(),
  item_id uuid references public.catalog_items(id) on delete set null,
  item_name text not null,
  movement_type text not null check (movement_type in ('in','out','adjustment')),
  quantity numeric(12,3) not null,
  unit_cost numeric(12,2) check (unit_cost is null or unit_cost >= 0),
  note text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists inventory_movements_created_at_idx on public.inventory_movements(created_at desc);
create index if not exists inventory_movements_created_by_idx on public.inventory_movements(created_by);
create index if not exists inventory_movements_item_id_idx on public.inventory_movements(item_id);

-- تفعيل حماية الصفوف على جميع الجداول العامة
