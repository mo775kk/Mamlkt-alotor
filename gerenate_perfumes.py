# ============================================
# دالة إنشاء المنتج
# ============================================
def create_product(name, brand, category, gender, sku):
    return {
        "name": name,
        "sku": sku,
        "brand": brand,
        "category": category,
        "gender": gender,
        "manufacturing_date": "2026-01-01",
        "stock": 100,
        "status": "active",
        "sizes": [
            {"size": "3ml", "price": 50},
            {"size": "5ml", "price": 75},
            {"size": "10ml", "price": 100},
            {"size": "22ml", "price": 130},
            {"size": "30ml", "price": 150},
            {"size": "50ml", "price": 200},
            {"size": "100ml", "price": 450}
        ]
    }

# ============================================
# توليد 1500 عطر
# ============================================
all_products = []

# إضافة العطور الحقيقية أولاً
for i, (name, brand, category, gender) in enumerate(real_perfumes, 1):
    sku = f"PERF-{i:04d}"
    all_products.append(create_product(name, brand, category, gender, sku))

# توليد العطور الإضافية
counter = len(real_perfumes) + 1
while len(all_products) < 1500:
    cat_choice = random.choice(["رجالي", "حريمي", "شرقي", "يونيسكس"])
    
    if cat_choice == "شرقي":
        name = f"{random.choice(extra_names_oriental)} {counter}"
        gender = "unisex"
    elif cat_choice == "رجالي":
        name = f"{random.choice(extra_names_male)} {counter}"
        gender = "male"
    elif cat_choice == "يونيسكس":
        name = f"{random.choice(extra_names_oriental)} {counter}"
        gender = "unisex"
    else:
        name = f"{random.choice(extra_names_female)} {counter}"
        gender = "female"
    
    brand = random.choice(extra_brands)
    sku = f"PERF-{counter:04d}"
    
    all_products.append(create_product(name, brand, cat_choice, gender, sku))
    counter += 1

# ============================================
# حفظ الملفات
